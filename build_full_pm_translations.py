# Helper to update keys inside a dictionary block
def update_dict_block(content, marker_start, marker_end, updates_dict):
    pos_start = content.find(marker_start)
    if pos_start == -1:
        raise ValueError(f"Marker {marker_start} not found")
    pos_end = content.find(marker_end, pos_start + len(marker_start))
    if pos_end == -1:
        raise ValueError(f"Marker {marker_end} not found")

    block = content[pos_start:pos_end]

    # Replace each key in block if present
    for k, v in updates_dict.items():
        escaped_v = v.replace('"', '\\"').replace('\n', '\\n')
        # match key: "..." or key: '...'
        pattern = rf'({re.escape(k)}\s*:\s*)(["\'])([\s\S]*?)\2(\s*,)'
        if re.search(pattern, block):
            block = re.sub(pattern, rf'\g<1>"{escaped_v}"\g<4>', block)
        else:
            # If not in block, insert before closing brace of dictionary
            print(f"Key {k} not found in {marker_start}, will append.")
            closing = block.rfind('};')
            if closing != -1:
                insert_str = f'  {k}: "{escaped_v}",\n'
                block = block[:closing] + insert_str + block[closing:]

    return content[:pos_start] + block + content[pos_end:]

