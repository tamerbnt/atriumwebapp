export const DICTIONARY: Record<SupportedLanguage, typeof TRANSLATIONS_EN> = {
  en: TRANSLATIONS_EN,
  fr: TRANSLATIONS_FR,
  ar: TRANSLATIONS_AR,
};

export type TranslationKey = keyof typeof TRANSLATIONS_EN;

/**
 * Direct translator function
 */
export function t(key: TranslationKey | string, lang: SupportedLanguage = 'en', fallback?: string): string {
  const dict = DICTIONARY[lang] || DICTIONARY.en;
  const val = (dict as any)?.[key];
  if (val) return val;
  const enVal = (DICTIONARY.en as any)?.[key];
  if (enVal) return enVal;
  return fallback !== undefined ? fallback : (key as string);
}



